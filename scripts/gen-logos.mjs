// Builds src/logos.js from the free Iconify "logos" set (full-color brand logos).
// Run: node scripts/gen-logos.mjs
import fs from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const set = require("@iconify-json/logos/icons.json");

// display name (lowercase) -> iconify logo key
const MAP = {
  python: "python", postgresql: "postgresql", vapi: "vapi-icon",
  "google calendar api": "google-calendar", pinecone: "pinecone-icon", cohere: "cohere-icon", "cohere rerank": "cohere-icon",
  openai: "openai-icon", elevenlabs: "elevenlabs-icon", supabase: "supabase-icon", go: "go", typescript: "typescript-icon",
  "next.js": "nextjs-icon", react: "react", redis: "redis", kafka: "kafka-icon", terraform: "terraform-icon", aws: "aws",
  docker: "docker-icon", nginx: "nginx", npm: "npm-icon", playwright: "playwright",
  vitest: "vitest", jest: "jest", cypress: "cypress", tensorflow: "tensorflow", "node.js": "nodejs-icon", express: "express",
  vite: "vitejs", claude: "claude-icon", "claude api": "anthropic-icon", gemini: "google-gemini", cloudflare: "cloudflare-icon",
  zod: "zod", resend: "resend-icon", java: "java", javascript: "javascript", pydantic: "pydantic", langchain: "langchain",
  "hugging face": "hugging-face-icon", vercel: "vercel-icon", postman: "postman-icon", groq: "groq", openrouter: "openrouter",
  "aws (ec2, rds, s3)": "aws", "aws ec2 / rds": "aws", "aws ec2 / lambda": "aws",
};
const out = {};
for (const [name, key] of Object.entries(MAP)) {
  const ic = set.icons[key] || (set.aliases?.[key] && set.icons[set.aliases[key].parent]);
  if (!ic) { console.warn("missing", key); continue; }
  out[name] = { body: ic.body, w: ic.width || set.width || 256, h: ic.height || set.height || 256 };
}
fs.writeFileSync(
  new URL("../src/logos.js", import.meta.url),
  "// Generated by scripts/gen-logos.mjs from @iconify-json/logos (free SVG Logos set). Do not edit by hand.\nexport const LOGOS = " +
    JSON.stringify(out) + ";\n"
);
console.log("wrote", Object.keys(out).length, "logos");
